import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import { randomUUID } from 'node:crypto';
test('central inicializa, sincroniza metadados sem binários e atualiza contador',async()=>{
  const calls=[],stored=new Map(),root={innerHTML:''};
  const record={appointments:[{id:1,results:[{name:'Resultado',data:'SEGREDO_BINARIO'}]}],meds:[],family:[]};
  const ctx=vm.createContext({KEY:'teste',db:{patients:[{id:1,name:'Paciente privado exemplo'}],activePatientId:1,records:{}},snapshot:()=>record,crypto:{randomUUID},localStorage:{getItem:key=>stored.get(key)||null,setItem:(key,value)=>stored.set(key,value)},document:{hidden:false,head:{append(){}},createElement:()=>({}),querySelector:()=>null,getElementById:()=>null},window:{addEventListener(){}},location:{search:'',protocol:'http:',hostname:'localhost',origin:'http://localhost:3000',replace(){}},URLSearchParams,Date,setInterval(){},render(){},family:()=>'',patients:()=>'',patientWelcome:()=>'',navigatePrimary(){},switchPatient(){},page:'home',selected:null,$:()=>root,nav:()=>'',head:()=>'',esc:value=>String(value??''),fmt:value=>value,toast(){},fetch:async(url,options)=>{
    const body=options.body&&JSON.parse(options.body);calls.push({url,body});
    const data=url.endsWith('/state')?{revision:0,patients:[],push:[]}:url.endsWith('/sync')?{revision:1}:{items:[{id:'notice',title:'Atualização',patient_name:'Paciente',created_at:Date.now(),read_at:null}],unread:1};
    return {ok:true,status:200,json:async()=>data};
  }});
  vm.runInContext(readFileSync('server/notifications-ui.js','utf8'),ctx);
  await new Promise(resolve=>setImmediate(resolve));
  assert.equal(calls.filter(call=>call.url.endsWith('/sync')).length,1);
  assert.doesNotMatch(JSON.stringify(calls),/SEGREDO_BINARIO/);
  assert.equal(vm.runInContext('notificationUnread',ctx),1);
  assert.match(vm.runInContext('notificationsView()',ctx),/Marcar todas como lidas/);
  assert.doesNotMatch(vm.runInContext('notificationsView()',ctx),/Acompanhantes e notificações|Autorizar acompanhantes|Conectar paciente|Gerenciar acesso|Envios push|notificationSettings/);
  const patientList=vm.runInContext('patients()',ctx);
  assert.match(patientList,/Copiar código do paciente/);
  assert.match(patientList,/data-patient-code="1"/);
  assert.doesNotMatch(patientList,/ID do paciente:/);
  assert.match(patientList,/Código do paciente/);
  const copied=[];
  ctx.navigator={clipboard:{writeText:async value=>copied.push(value)}};
  await vm.runInContext("copyPatientCode('ABCD-1234-EF00-5678-9999')",ctx);
  assert.equal(copied[0],'ABCD-1234-EF00-5678-9999');
  vm.runInContext("page='notifications';render()",ctx);
  assert.match(root.innerHTML,/Atualização/);
  ctx.invite={message:'💚 Você recebeu um convite!\nOlá! 👋\nPaciente privado exemplo\n🔐 Código de vinculação: codigo-teste\n📲 Baixe o app: https://app.example.test/convite/exemplo'};
  const share=new URL(vm.runInContext('whatsappInviteURL(invite)',ctx));
  assert.equal(share.origin,'https://api.whatsapp.com');
  const message=share.searchParams.get('text');
  assert.match(message,/codigo-teste/);
  assert.match(message,/Paciente privado exemplo/);
  for(const symbol of ['💚','👋','🔐','📲'])assert.ok(message.includes(symbol));
  assert.equal(message,ctx.invite.message);
  assert.ok(!message.includes('\uFFFD'));
  assert.doesNotMatch(message,/localhost|SEGREDO_BINARIO/);
  const destinations=[];
  ctx.location.assign=value=>destinations.push(value);
  ctx.fetch=async url=>({ok:true,status:200,json:async()=>url.includes('/state')?{patients:[{id:'owner:1'}]}:{message:ctx.invite.message}});
  ctx.shareForm={querySelector:()=>({disabled:false})};
  await vm.runInContext('createFamilyWhatsAppInvite({preventDefault(){},target:shareForm})',ctx);
  assert.equal(destinations.length,1);
  assert.equal(new URL(destinations[0]).origin,'https://api.whatsapp.com');
  assert.equal(new URL(destinations[0]).searchParams.get('text'),ctx.invite.message);
  ctx.fetch=async()=>({ok:true,status:200,json:async()=>({id:'owner:p1',name:'Paciente compartilhado',data:{appointments:[{id:10,name:'Consulta original',date:'2026-12-01',time:'08:00',status:'Agendado',postNotes:'Informação original'}],meds:[],family:[],patientInfo:{}}})});
  await vm.runInContext("openSharedPatient('owner:p1','agenda')",ctx);
  assert.match(root.innerHTML,/Consulta original/);
  await vm.runInContext("openSharedRecord('10','appointment')",ctx);
  assert.match(root.innerHTML,/Informação original/);
  ctx.fetch=async()=>({ok:false,status:403,json:async()=>({error:'Acesso revogado'})});
  await vm.runInContext("openSharedPatient('owner:p1')",ctx);
  assert.match(root.innerHTML,/Acesso revogado/);
});
